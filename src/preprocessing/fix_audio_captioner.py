import pandas as pd
from pathlib import Path


CSV_PATH = Path("data/metadata/captions.csv")


df = pd.read_csv(CSV_PATH)


# ------------------------------------------------------------
# Fix track_id and audio_path
# ------------------------------------------------------------

for index, row in df.iterrows():

    filename = str(row["filename"])

    if not filename or filename == "nan":
        continue

    # Extract existing numeric part if available
    existing_track_id = str(row.get("track_id", ""))

    if existing_track_id.startswith("track_"):
        track_id = existing_track_id

    else:
        track_id = f"track_{index + 1:03d}"

    df.at[index, "track_id"] = track_id

    df.at[index, "audio_path"] = str(
        Path("data/raw") / filename
    )


# ------------------------------------------------------------
# Ensure caption_source exists
# ------------------------------------------------------------

if "caption_source" not in df.columns:
    df["caption_source"] = ""

# Existing successful Gemini captions from previous run
# were generated by Gemini.
for index, row in df.iterrows():

    if (
        str(row["status"]).lower() == "success"
        and not str(row["caption_source"]).strip()
    ):
        df.at[index, "caption_source"] = "gemini"


# ------------------------------------------------------------
# Save
# ------------------------------------------------------------

df.to_csv(
    CSV_PATH,
    index=False
)


print("=" * 60)
print("CAPTION METADATA REPAIR COMPLETE")
print("=" * 60)

print(
    f"Total rows: {len(df)}"
)

print(
    f"Successful: "
    f"{(df['status'].str.lower() == 'success').sum()}"
)

print(
    f"Failed: "
    f"{(df['status'].str.lower() == 'failed').sum()}"
)

print("\nTrack metadata:")

print(
    df[
        [
            "track_id",
            "filename",
            "audio_path",
            "status",
            "caption_source"
        ]
    ].to_string(index=False)
)

print(
    f"\nSaved → {CSV_PATH}"
)